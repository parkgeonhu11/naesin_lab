-- =====================================================================
-- 내신랩 데이터베이스 (Supabase SQL Editor에 통째로 붙여 넣고 Run)
-- 핵심 원칙
--   1) 정답은 question_answers 테이블에만 있고, 학생 브라우저는 절대 못 읽는다.
--   2) 채점과 점수 지급은 아래 서버 함수(submit_answer)만 할 수 있다.
--   3) 같은 문제로 점수를 두 번 받을 수 없다 (고유 제약 조건).
-- 분류 체계: 과목(subject) → 대단원(unit) → 세부 유형(topic) → 난이도(difficulty)
-- 문제 유형: mc = 객관식, short = 단답형
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------- 테이블 ----------
create table if not exists public.subjects (
  code  text primary key,
  name  text not null,
  sort  int  not null default 0
);

-- 분류 구조: 과목 → 대단원 → 세부 유형 (문제가 없어도 목록에 보이도록 따로 저장)
create table if not exists public.categories (
  subject text not null references public.subjects(code),
  unit    text not null,
  topic   text not null default '',
  sort    int  not null default 0,
  primary key (subject, unit, topic)
);

create table if not exists public.questions (
  id          uuid primary key default gen_random_uuid(),
  no          int  generated by default as identity (start with 1001) unique,   -- 문제 번호 (1001번부터)
  subject     text not null references public.subjects(code),
  unit        text not null default '',                 -- 대단원
  topic       text not null default '',                 -- 세부 유형
  qtype       text not null default 'mc' check (qtype in ('mc','short')),
  difficulty  smallint not null check (difficulty between 1 and 5),
  body        text not null check (char_length(body) between 1 and 1000),
  choices     jsonb not null default '[]'::jsonb check (jsonb_typeof(choices) = 'array' and jsonb_array_length(choices) <= 5),
  explanation text not null default '',
  source      text not null default '',                 -- 출처 (예: 내신랩 자체 제작, 학생 제안)
  status      text not null default 'published' check (status in ('pending','published','rejected')),
  author      uuid,
  author_nick text not null default '',
  sort        int not null default 0,
  created_at  timestamptz not null default now(),
  check (qtype = 'short' or jsonb_array_length(choices) >= 2)
);
create index if not exists questions_subject_idx on public.questions(subject, unit, topic, status);

-- 정답: 아무도 직접 못 읽음 (RLS 정책 없음). 서버 함수만 접근.
-- 객관식은 answer(0부터 시작하는 보기 번호), 단답형은 answer_text('정답1|정답2' 처럼 여러 개 허용)
create table if not exists public.question_answers (
  question_id uuid primary key references public.questions(id) on delete cascade,
  answer      smallint,
  answer_text text,
  check (answer is not null or answer_text is not null)
);

create table if not exists public.profiles (
  user_id    uuid primary key,
  nickname   text not null check (char_length(nickname) between 1 and 12),
  created_at timestamptz not null default now()
);

create table if not exists public.attempts (
  id          bigserial primary key,
  user_id     uuid not null,
  question_id uuid not null references public.questions(id) on delete cascade,
  choice      smallint,
  text_answer text,
  is_correct  boolean not null,
  created_at  timestamptz not null default now()
);
create index if not exists attempts_user_idx on public.attempts(user_id, question_id);
create index if not exists attempts_q_idx on public.attempts(question_id);

-- 점수 지급 내역: reason = 'solve'(문제 풀이) | 'author'(출제 보너스)
create table if not exists public.score_events (
  id          bigserial primary key,
  user_id     uuid not null,
  question_id uuid references public.questions(id) on delete set null,
  reason      text not null check (reason in ('solve','author')),
  subject     text,
  points      int  not null,
  created_at  timestamptz not null default now(),
  unique (user_id, question_id, reason)          -- 같은 문제 중복 지급 방지
);
create index if not exists score_events_time_idx on public.score_events(created_at);

-- 오답 감점 내역 (points는 음수). 두 번째 오답부터 틀릴 때마다 한 줄씩 쌓인다.
create table if not exists public.score_penalties (
  id          bigserial primary key,
  user_id     uuid not null,
  question_id uuid references public.questions(id) on delete set null,
  subject     text,
  points      int  not null check (points < 0),
  created_at  timestamptz not null default now()
);
create index if not exists score_penalties_user_idx on public.score_penalties(user_id, question_id);

-- 관리자 이메일 목록 (아무도 직접 못 읽음)
create table if not exists public.admin_emails (
  email text primary key
);

