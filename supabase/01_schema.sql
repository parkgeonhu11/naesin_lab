-- ---------- 공통 함수 ----------
create or replace function public.points_for(d smallint)
returns int language sql immutable as $$
  select case d when 1 then 5 when 2 then 10 when 3 then 20 when 4 then 35 else 50 end
$$;

-- 단답형 비교용: 소문자로, 띄어쓰기·문장부호·도(°) 기호 제거
create or replace function public.norm_answer(t text)
returns text language sql immutable as $$
  select regexp_replace(lower(coalesce(t,'')), '[\s\.,!?''"·°~()\[\]]', '', 'g')
$$;

create or replace function public.first_answer(t text)
returns text language sql immutable as $$
  select btrim(split_part(coalesce(t,''), '|', 1))
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from admin_emails
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  ) and coalesce(auth.jwt() ->> 'email', '') <> ''
$$;

create or replace function public.week_start()
returns timestamptz language sql stable as $$
  -- 한국 시간 기준 이번 주 월요일 0시
  select (date_trunc('week', now() at time zone 'Asia/Seoul')) at time zone 'Asia/Seoul'
$$;

-- 분류가 없으면 새로 등록 (문제 공개·추가 때 자동 호출)
create or replace function public.ensure_category(p_subject text, p_unit text, p_topic text)
returns void language sql security definer set search_path = public as $$
  insert into categories(subject, unit, topic, sort)
  values (p_subject, coalesce(p_unit,''), coalesce(p_topic,''), 1000)
  on conflict do nothing
$$;
revoke all on function public.ensure_category(text,text,text) from public, anon, authenticated;

