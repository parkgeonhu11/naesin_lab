-- 닉네임 정하기/바꾸기
create or replace function public.set_nickname(p_nick text)
returns void language plpgsql security definer set search_path = public as $$
declare n text := btrim(coalesce(p_nick,''));
begin
  if auth.uid() is null then raise exception '로그인 세션이 없어'; end if;
  if char_length(n) < 1 or char_length(n) > 12 then raise exception '닉네임은 1~12자'; end if;
  insert into profiles(user_id, nickname) values (auth.uid(), n)
  on conflict (user_id) do update set nickname = excluded.nickname;
end $$;

-- 답안 제출 → 서버 채점 → 점수 지급
-- 객관식은 p_choice(0부터), 단답형은 p_text 로 보낸다.
drop function if exists public.submit_answer(uuid, smallint);
-- 채점 규칙
--   처음에 맞히면 만점, 한 번이라도 틀린 뒤 맞히면 절반
--   첫 번째 오답은 봐주고, 두 번째 오답부터는 틀릴 때마다 배점의 25%를 바로 감점 (문제당 최대 4번 = 배점만큼)
--   똑같은 오답을 다시 내면 감점하지 않는다
--   그래서 객관식을 1번부터 5번까지 찍어서 마지막에 맞히면 합계가 마이너스가 된다
create or replace function public.submit_answer(p_question uuid, p_choice smallint default null, p_text text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  q   questions%rowtype;
  qa  question_answers%rowtype;
  ok  boolean;
  tried int;
  repeat_wrong boolean;
  full_pts int;
  pts int := 0;
  pen int := 0;
  done boolean;
  my_key text;
begin
  if uid is null then raise exception '로그인 세션이 없어'; end if;
  -- 같은 사람이 같은 문제를 동시에 여러 번 보내도 한 번씩 처리
  perform pg_advisory_xact_lock(hashtext(uid::text || p_question::text));

  select * into q from questions where id = p_question and status = 'published';
  if not found then raise exception '문제를 찾을 수 없어'; end if;
  select * into qa from question_answers where question_id = p_question;

  if q.qtype = 'short' then
    if norm_answer(p_text) = '' then raise exception '답을 입력해 줘'; end if;
    select exists (
      select 1 from unnest(string_to_array(qa.answer_text, '|')) a where norm_answer(a) = norm_answer(p_text)
    ) into ok;
    my_key := norm_answer(p_text);
  else
    if p_choice is null then raise exception '보기를 골라 줘'; end if;
    ok := (p_choice = qa.answer);
    my_key := p_choice::text;
  end if;

  select exists(select 1 from score_events where user_id = uid and question_id = p_question and reason = 'solve') into done;
  if done then
    return jsonb_build_object('correct', ok, 'already', true, 'points', 0,
                              'answer', qa.answer, 'answer_text', first_answer(qa.answer_text), 'explanation', q.explanation);
  end if;

  -- 지금까지 낸 서로 다른 오답 개수
  select count(distinct coalesce(a.choice::text, norm_answer(a.text_answer))),
         bool_or(coalesce(a.choice::text, norm_answer(a.text_answer)) = my_key)
    into tried, repeat_wrong
  from attempts a where a.user_id = uid and a.question_id = p_question and not a.is_correct;
  repeat_wrong := coalesce(repeat_wrong, false);

  insert into attempts(user_id, question_id, choice, text_answer, is_correct)
  values (uid, p_question, p_choice, left(p_text, 200), ok);

  full_pts := case when q.author = uid then 0 else points_for(q.difficulty) end;   -- 내가 낸 문제는 0점

  if not ok then
    if repeat_wrong then
      return jsonb_build_object('correct', false, 'points', 0, 'penalty', 0, 'tried', tried, 'repeat', true);
    end if;
    -- 이번이 (tried + 1)번째 오답. 첫 오답은 봐주고, 2~5번째 오답만 감점
    if tried between 1 and 4 then
      pen := round(full_pts * 0.25);
      if pen > 0 then
        insert into score_penalties(user_id, question_id, subject, points)
        values (uid, p_question, q.subject, -pen);
      end if;
    end if;
    return jsonb_build_object('correct', false, 'points', 0, 'penalty', pen, 'tried', tried + 1,
                              'next_penalty', case when tried + 1 between 1 and 4 then round(full_pts * 0.25) else 0 end);
  end if;

  pts := full_pts;
  if tried > 0 then pts := pts / 2; end if;        -- 한 번이라도 틀렸으면 절반
  insert into score_events(user_id, question_id, reason, subject, points)
  values (uid, p_question, 'solve', q.subject, pts)
  on conflict do nothing;
  return jsonb_build_object('correct', true, 'points', pts, 'answer', qa.answer,
                            'answer_text', first_answer(qa.answer_text), 'explanation', q.explanation,
                            'lost', (select coalesce(-sum(points),0) from score_penalties
                                     where user_id = uid and question_id = p_question));
end $$;

-- 포기하고 정답 보기 (0점으로 기록)
create or replace function public.reveal_answer(p_question uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); q questions%rowtype; qa question_answers%rowtype;
begin
  if uid is null then raise exception '로그인 세션이 없어'; end if;
  select * into q from questions where id = p_question and status = 'published';
  if not found then raise exception '문제를 찾을 수 없어'; end if;
  select * into qa from question_answers where question_id = p_question;
  insert into score_events(user_id, question_id, reason, subject, points)
  values (uid, p_question, 'solve', q.subject, 0) on conflict do nothing;
  return jsonb_build_object('answer', qa.answer, 'answer_text', first_answer(qa.answer_text), 'explanation', q.explanation);
end $$;

-- 내 풀이 상태 (문제별: 획득 점수 / 틀린 횟수 / 정답은 끝난 문제만)
drop function if exists public.my_progress();
create or replace function public.my_progress()
returns table(question_id uuid, points int, tried boolean, wrong int, answer smallint, answer_text text, explanation text)
language sql stable security definer set search_path = public as $$
  with s as (select question_id, points from score_events where user_id = auth.uid() and reason = 'solve'),
       a as (select question_id,
                    count(distinct coalesce(choice::text, norm_answer(text_answer))) filter (where not is_correct)::int as wrong
             from attempts where user_id = auth.uid() group by question_id)
  select coalesce(s.question_id, a.question_id), s.points, coalesce(a.wrong, 0) > 0, coalesce(a.wrong, 0),
         case when s.question_id is not null then qa.answer end,
         case when s.question_id is not null then first_answer(qa.answer_text) end,
         case when s.question_id is not null then q.explanation end
  from s full join a on a.question_id = s.question_id
  left join question_answers qa on qa.question_id = coalesce(s.question_id, a.question_id)
  left join questions q on q.id = coalesce(s.question_id, a.question_id)
$$;

-- 단원별 성적 분석 (과목·대단원·세부 유형 단위)
create or replace function public.my_unit_stats()
returns table(subject text, unit text, topic text, total bigint, solved bigint, attempted bigint,
              submissions bigint, correct_submissions bigint)
language sql stable security definer set search_path = public as $$
  select q.subject, q.unit, q.topic,
         count(*)::bigint,
         count(*) filter (where s.points > 0)::bigint,
         count(*) filter (where a.cnt > 0 or s.points is not null)::bigint,
         coalesce(sum(a.cnt), 0)::bigint,
         coalesce(sum(a.ok), 0)::bigint
  from questions q
  left join (select question_id, points from score_events where user_id = auth.uid() and reason = 'solve') s on s.question_id = q.id
  left join (select question_id, count(*) cnt, count(*) filter (where is_correct) ok
             from attempts where user_id = auth.uid() group by question_id) a on a.question_id = q.id
  where q.status = 'published'
  group by q.subject, q.unit, q.topic
  order by q.subject, q.unit, q.topic
$$;

-- 랭킹: p_subject = 'all' 또는 과목 코드, p_period = 'all' 또는 'week'
drop function if exists public.leaderboard(text,text,int);
create or replace function public.leaderboard(p_subject text default 'all', p_period text default 'all', p_limit int default 100)
returns table(rank bigint, user_id uuid, nickname text, points bigint, solved bigint, submissions bigint)
language sql stable security definer set search_path = public as $$
  with e as (
    select se.user_id, se.points, se.reason
    from score_events se
    where (p_subject = 'all' or se.subject = p_subject)
      and (p_period <> 'week' or se.created_at >= week_start())
    union all
    select sp.user_id, sp.points, 'penalty'
    from score_penalties sp
    where (p_subject = 'all' or sp.subject = p_subject)
      and (p_period <> 'week' or sp.created_at >= week_start())
  ), t as (
    select e.user_id, sum(e.points)::bigint as points,
           count(*) filter (where e.reason = 'solve' and e.points > 0)::bigint as solved
    from e group by e.user_id
  ), s as (
    select a.user_id, count(*)::bigint as submissions
    from attempts a join questions q on q.id = a.question_id
    where (p_subject = 'all' or q.subject = p_subject)
      and (p_period <> 'week' or a.created_at >= week_start())
    group by a.user_id
  )
  select rank() over (order by t.points desc), t.user_id, coalesce(p.nickname, '이름 없음'), t.points, t.solved,
         coalesce(s.submissions, 0)
  from t left join profiles p on p.user_id = t.user_id
         left join s on s.user_id = t.user_id
  where t.points > 0
  order by t.points desc, t.user_id
  limit greatest(1, least(p_limit, 500))
$$;

-- 문제 목록 + 통계 (맞힌 사람, 제출 수, 정답률). 정답은 포함하지 않는다.
drop function if exists public.problem_list();
create or replace function public.problem_list()
returns table(no int, id uuid, subject text, unit text, topic text, qtype text, difficulty smallint, title text,
              solvers bigint, submissions bigint, accuracy int, source text, author_nick text, from_student boolean)
language sql stable security definer set search_path = public as $$
  select q.no, q.id, q.subject, q.unit, q.topic, q.qtype, q.difficulty,
         left(regexp_replace(split_part(q.body, E'\n', 1), '\s+', ' ', 'g'), 60),
         coalesce(st.solvers, 0), coalesce(st.subs, 0), coalesce(st.acc, 0),
         q.source, q.author_nick, q.author is not null
  from questions q
  left join (
    select question_id,
           count(distinct user_id) filter (where is_correct) solvers,
           count(*) subs,
           round(100.0 * count(*) filter (where is_correct) / nullif(count(*), 0))::int acc
    from attempts group by question_id
  ) st on st.question_id = q.id
  where q.status = 'published'
  order by q.no
$$;

-- 채점 현황 (최근 제출). 누가 무슨 답을 썼는지는 공개하지 않고 결과만 보여 준다.
drop function if exists public.recent_submissions(int, boolean);
create or replace function public.recent_submissions(p_limit int default 50, p_only_me boolean default false)
returns table(id bigint, nickname text, is_me boolean, problem_no int, subject text, title text, is_correct boolean, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select a.id, coalesce(p.nickname, '이름 없음'), a.user_id = auth.uid(), q.no, q.subject,
         left(regexp_replace(split_part(q.body, E'\n', 1), '\s+', ' ', 'g'), 40), a.is_correct, a.created_at
  from attempts a
  join questions q on q.id = a.question_id
  left join profiles p on p.user_id = a.user_id
  where (not p_only_me or a.user_id = auth.uid())
  order by a.id desc
  limit greatest(1, least(p_limit, 200))
$$;

-- 문제 제안 (관리자가 승인해야 공개, 승인되면 출제 보너스 +5점, 최대 20문제)
-- 난이도는 1~5 모두 가능. 어려움(4)·최상위(5)는 관리자가 검토할 수 있게 해설(풀이)을 꼭 써야 한다.
drop function if exists public.suggest_question(text,text,smallint,text,jsonb,smallint,text);
create or replace function public.suggest_question(
  p_subject text, p_unit text, p_topic text, p_qtype text, p_difficulty smallint, p_body text,
  p_choices jsonb, p_answer smallint, p_answer_text text, p_explanation text)
returns uuid language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); nid uuid; pend int; nick text;
begin
  if uid is null then raise exception '로그인 세션이 없어'; end if;
  if p_difficulty not between 1 and 5 then raise exception '난이도는 1~5만 가능'; end if;
  if p_difficulty >= 4 and length(trim(coalesce(p_explanation,''))) < 10 then
    raise exception '어려움·최상위 문제는 풀이 과정을 해설에 꼭 써 줘'; end if;
  if p_qtype = 'mc' and (p_answer is null or p_answer < 0 or p_answer >= jsonb_array_length(p_choices)) then
    raise exception '정답 번호가 보기 범위를 벗어났어'; end if;
  if p_qtype = 'short' and norm_answer(p_answer_text) = '' then raise exception '단답형 정답을 입력해 줘'; end if;
  select count(*) into pend from questions where author = uid and status = 'pending';
  if pend >= 10 then raise exception '검토 대기 문제가 10개를 넘었어. 승인될 때까지 기다려 줘'; end if;
  select nickname into nick from profiles where user_id = uid;
  insert into questions(subject, unit, topic, qtype, difficulty, body, choices, explanation, source, status, author, author_nick, sort)
  values (p_subject, left(coalesce(p_unit,''),40), left(coalesce(p_topic,''),40), p_qtype, p_difficulty, p_body,
          case when p_qtype = 'short' then '[]'::jsonb else p_choices end,
          left(coalesce(p_explanation,''),1000), '학생 제안', 'pending', uid, coalesce(nick,''), 100000)
  returning id into nid;
  insert into question_answers(question_id, answer, answer_text)
  values (nid, case when p_qtype = 'mc' then p_answer end, case when p_qtype = 'short' then left(p_answer_text, 200) end);
  return nid;
end $$;

-- 내 요약: 홈 화면 대시보드용 (점수, 순위, 맞힌 문제, 정답률, 오늘 푼 문제, 연속 학습일)
create or replace function public.my_summary()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  today date := (now() at time zone 'Asia/Seoul')::date;
  total bigint; wk bigint; d date; streak int := 0;
begin
  if uid is null then return null; end if;
  select coalesce(sum(x.points), 0) into total from (
    select s.points from score_events s where s.user_id = uid
    union all select p.points from score_penalties p where p.user_id = uid) x;
  select coalesce(sum(x.points), 0) into wk from (
    select s.points from score_events s where s.user_id = uid and s.created_at >= week_start()
    union all select p.points from score_penalties p where p.user_id = uid and p.created_at >= week_start()) x;
  -- 연속 학습일: 오늘(없으면 어제)부터 거꾸로 하루도 빠짐없이 제출한 날 수
  d := today;
  if not exists (select 1 from attempts a where a.user_id = uid and (a.created_at at time zone 'Asia/Seoul')::date = d) then
    d := today - 1;
  end if;
  while exists (select 1 from attempts a where a.user_id = uid and (a.created_at at time zone 'Asia/Seoul')::date = d) loop
    streak := streak + 1; d := d - 1;
    exit when streak > 366;
  end loop;
  return (
    with pts as (
      select y.user_id, sum(y.points) as p from (
        select s.user_id, s.points from score_events s
        union all select q.user_id, q.points from score_penalties q) y
      group by y.user_id)
    select jsonb_build_object(
      'points', total,
      'week', wk,
      'rank', case when total > 0 then 1 + (select count(*) from pts where pts.p > total) end,
      'players', (select count(*) from pts where pts.p > 0),
      'solved', (select count(*) from score_events s where s.user_id = uid and s.reason = 'solve' and s.points > 0),
      'revealed', (select count(*) from score_events s where s.user_id = uid and s.reason = 'solve' and s.points = 0),
      'submissions', (select count(*) from attempts a where a.user_id = uid),
      'correct_submissions', (select count(*) from attempts a where a.user_id = uid and a.is_correct),
      'today_solved', (select count(*) from score_events s where s.user_id = uid and s.reason = 'solve' and s.points > 0
                         and (s.created_at at time zone 'Asia/Seoul')::date = today),
      'today_submissions', (select count(*) from attempts a where a.user_id = uid and (a.created_at at time zone 'Asia/Seoul')::date = today),
      'streak', streak,
      -- 이번 주에 풀어 본 과목 수 (주간 미션: 서로 다른 3과목)
      'week_subjects', (select count(distinct q.subject) from attempts a join questions q on q.id = a.question_id
                        where a.user_id = uid and a.created_at >= week_start()),
      -- 이번 주 / 지난주 정답률 (성장 기록)
      'week_subs', (select count(*) from attempts a where a.user_id = uid and a.created_at >= week_start()),
      'week_ok', (select count(*) from attempts a where a.user_id = uid and a.is_correct and a.created_at >= week_start()),
      'last_subs', (select count(*) from attempts a where a.user_id = uid
                     and a.created_at >= week_start() - interval '7 days' and a.created_at < week_start()),
      'last_ok', (select count(*) from attempts a where a.user_id = uid and a.is_correct
                   and a.created_at >= week_start() - interval '7 days' and a.created_at < week_start()),
      -- 최근 7일 날짜별 맞힌 문제 수 (오래된 날부터)
      'daily', (select jsonb_agg(jsonb_build_object('d', g.d, 'n',
                  (select count(*) from score_events s where s.user_id = uid and s.reason = 'solve' and s.points > 0
                     and (s.created_at at time zone 'Asia/Seoul')::date = g.d)) order by g.d)
                from generate_series(today - 6, today, interval '1 day') as g0(t), lateral (select g0.t::date as d) g))
  );
end $$;
revoke all on function public.my_summary() from public, anon;
grant execute on function public.my_summary() to authenticated;

-- ---------- 관리자 함수 (admin_emails 에 있는 이메일로 로그인해야 실행됨) ----------
drop function if exists public.admin_pending();
create or replace function public.admin_pending()
returns table(id uuid, subject text, unit text, topic text, qtype text, difficulty smallint, body text, choices jsonb,
              answer smallint, answer_text text, explanation text, author_nick text, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then raise exception '관리자만 가능해'; end if;
  return query
    select q.id, q.subject, q.unit, q.topic, q.qtype, q.difficulty, q.body, q.choices, qa.answer, qa.answer_text,
           q.explanation, q.author_nick, q.created_at
    from questions q join question_answers qa on qa.question_id = q.id
    where q.status = 'pending' order by q.created_at;
end $$;

-- 승인할 때 관리자가 난이도를 고칠 수 있다 (p_difficulty, 비우면 그대로)
drop function if exists public.admin_review(uuid, boolean);
create or replace function public.admin_review(p_question uuid, p_approve boolean, p_difficulty smallint default null)
returns void language plpgsql security definer set search_path = public as $$
declare q questions%rowtype; bonus_count int;
begin
  if not is_admin() then raise exception '관리자만 가능해'; end if;
  if p_difficulty is not null and p_difficulty not between 1 and 5 then raise exception '난이도는 1~5만 가능'; end if;
  select * into q from questions where id = p_question for update;
  if not found then raise exception '문제를 찾을 수 없어'; end if;
  update questions set status = case when p_approve then 'published' else 'rejected' end,
                       difficulty = case when p_approve and p_difficulty is not null then p_difficulty else difficulty end
  where id = p_question;
  if p_approve then perform ensure_category(q.subject, q.unit, q.topic); end if;
  if p_approve and q.author is not null then
    select count(*) into bonus_count from score_events where user_id = q.author and reason = 'author';
    if bonus_count < 20 then
      insert into score_events(user_id, question_id, reason, subject, points)
      values (q.author, q.id, 'author', null, 5) on conflict do nothing;
    end if;
  end if;
end $$;

drop function if exists public.admin_add_question(text,text,smallint,text,jsonb,smallint,text);
create or replace function public.admin_add_question(
  p_subject text, p_unit text, p_topic text, p_qtype text, p_difficulty smallint, p_body text,
  p_choices jsonb, p_answer smallint, p_answer_text text, p_explanation text, p_source text)
returns uuid language plpgsql security definer set search_path = public as $$
declare nid uuid;
begin
  if not is_admin() then raise exception '관리자만 가능해'; end if;
  if p_qtype = 'mc' and (p_answer is null or p_answer < 0 or p_answer >= jsonb_array_length(p_choices)) then
    raise exception '정답 번호가 보기 범위를 벗어났어'; end if;
  if p_qtype = 'short' and norm_answer(p_answer_text) = '' then raise exception '단답형 정답을 입력해 줘'; end if;
  insert into questions(subject, unit, topic, qtype, difficulty, body, choices, explanation, source, status, author_nick, sort)
  values (p_subject, coalesce(p_unit,''), coalesce(p_topic,''), p_qtype, p_difficulty, p_body,
          case when p_qtype = 'short' then '[]'::jsonb else p_choices end,
          coalesce(p_explanation,''), coalesce(nullif(p_source,''), '관리자 출제'), 'published', '관리자', 50000)
  returning id into nid;
  insert into question_answers(question_id, answer, answer_text)
  values (nid, case when p_qtype = 'mc' then p_answer end, case when p_qtype = 'short' then p_answer_text end);
  perform ensure_category(p_subject, p_unit, p_topic);
  return nid;
end $$;

-- 관리자: 분류(대단원·세부 유형) 추가 / 삭제
create or replace function public.admin_add_category(p_subject text, p_unit text, p_topic text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception '관리자만 가능해'; end if;
  if btrim(coalesce(p_unit,'')) = '' then raise exception '대단원 이름을 입력해 줘'; end if;
  insert into categories(subject, unit, topic, sort) values (p_subject, btrim(p_unit), btrim(coalesce(p_topic,'')), 1000)
  on conflict do nothing;
end $$;

